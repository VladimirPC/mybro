export function minutesSince(from: number, now = Date.now()) {
  return Math.max(0, (now - from) / 60000);
}

export function recoveryProgress(minutesWithout: number) {
  const reached = RECOVERY.filter((m) => minutesWithout >= m.afterMin);
  const next = RECOVERY.find((m) => minutesWithout < m.afterMin) ?? null;
  const last = reached[reached.length - 1] ?? null;
  let fraction = 0;
  if (next) {
    const prevAt = last?.afterMin ?? 0;
    fraction = (minutesWithout - prevAt) / (next.afterMin - prevAt);
  } else {
    fraction = 1;
  }
  return { reached, next, last, fraction: Math.min(1, Math.max(0, fraction)) };
}
