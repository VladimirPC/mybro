export const KIND_LABEL: Record<FactKind, string> = {
  harm: "Вред",
  body: "Тело",
  mind: "Привычка",
  proof: "Польза снижения",
};

const BENEFIT_KINDS: FactKind[] = ["body", "mind", "proof"];

function pickFrom(list: Fact[], seed: string, avoidId?: string | null): Fact {
  const usable = avoidId ? list.filter((f) => f.id !== avoidId) : list;
  const pool = usable.length ? usable : list;
  let hash = 0;
  for (let i = 0; i < seed.length; i += 1) {
    hash = (hash * 33 + seed.charCodeAt(i)) >>> 0;
  }
  return pool[hash % pool.length] ?? FACTS[0]!;
}

export function pickBenefitFact(seed: string, avoidId?: string | null): Fact {
  const list = FACTS.filter((f) => BENEFIT_KINDS.includes(f.kind));
  if (avoidId) {
    const idx = list.findIndex((f) => f.id === avoidId);
    if (idx >= 0) return list[(idx + 1) % list.length]!;
  }
  return pickFrom(list, seed, avoidId);
}

export function pickHarmFact(seed: string, avoidId?: string | null): Fact {
  return pickFrom(
    FACTS.filter((f) => f.kind === "harm"),
    `${seed}-harm`,
    avoidId,
  );
}

export function pickFact(seed: string, avoidId?: string | null): Fact {
  return pickBenefitFact(seed, avoidId);
}
